export const SPECIES: Species[] = ROWS.map(
  ([id, name, latin, family, form, light, waterDays, feedDays, humidity, petSafe, difficulty, tip]) => ({
    id,
    name,
    latin,
    family,
    form,
    light,
    waterDays,
    feedDays,
    humidity,
    petSafe,
    difficulty,
    tip,
  }),
);

const BY_ID = new Map(SPECIES.map((s) => [s.id, s]));

export function getSpecies(id: string): Species | undefined {
  return BY_ID.get(id);
}

export function isSpeciesId(id: unknown): id is string {
  return typeof id === "string" && BY_ID.has(id);
}

/** How far a space's light is from what a species wants: negative is too dark, positive too bright. */
export function lightGap(wants: Light, gets: Light): number {
  return LIGHT_IDS.indexOf(gets) - LIGHT_IDS.indexOf(wants);
}
