export type Form = "foliage" | "flowering" | "succulent" | "cactus" | "fern" | "palm" | "tree" | "vine" | "herb";

export const FORMS: Record<Form, { label: string }> = {
  foliage: { label: "Foliage" },
  flowering: { label: "Flowering" },
  succulent: { label: "Succulent" },
  cactus: { label: "Cactus" },
  fern: { label: "Fern" },
  palm: { label: "Palm" },
  tree: { label: "Tree" },
  vine: { label: "Vine & trailing" },
  herb: { label: "Herb" },
};

export const FORM_IDS = Object.keys(FORMS) as Form[];

/** How much light a plant wants, or a space gets. Ordered from darkest to brightest. */
export type Light = "low" | "medium" | "bright" | "direct";

export const LIGHTS: Record<Light, { label: string; short: string; hint: string }> = {
  low: { label: "Low light", short: "Low", hint: "Far from windows, or a north-facing room" },
  medium: { label: "Medium light", short: "Medium", hint: "A few feet from a window" },
  bright: { label: "Bright indirect", short: "Bright", hint: "Near a sunny window, out of direct sun" },
  direct: { label: "Direct sun", short: "Direct", hint: "On a sunny sill or outdoors" },
};

export const LIGHT_IDS = Object.keys(LIGHTS) as Light[];

export type Humidity = "low" | "medium" | "high";
export const HUMIDITY: Record<Humidity, { label: string }> = {
  low: { label: "Low" },
  medium: { label: "Average" },
  high: { label: "High" },
};

export type Difficulty = "easy" | "moderate" | "hard";
export const DIFFICULTY: Record<Difficulty, { label: string }> = {
  easy: { label: "Easy" },
  moderate: { label: "Moderate" },
  hard: { label: "Fussy" },
};

export type Species = {
  /** Stable id, lowercase-kebab-case. Stored in the database, so never rename one. */
  id: string;
  name: string;
  /** Botanical name, shown in italics. */
  latin: string;
  family: string;
  form: Form;
  light: Light;
  /** Typical days between waterings indoors. */
  waterDays: number;
  /** Typical days between feeds in the growing season, or null if it rarely needs feeding. */
  feedDays: number | null;
  humidity: Humidity;
  /** Non-toxic to cats and dogs, by common references. Always double-check for your own pets. */
  petSafe: boolean;
  difficulty: Difficulty;
  /** A one-line care tip. */
  tip: string;
};

